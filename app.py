import streamlit as st
from falkordb import FalkorDB
from src.graphsleuth.db import get_graph, ping_database
from src.graphsleuth.seed import seed_demo_data
from src.graphsleuth.agent import list_accounts, investigate, get_memory
from src.graphsleuth.config import get_config

st.set_page_config(page_title="GraphSleuth AI", page_icon="🕵️", layout="wide")
st.title("🕵️ GraphSleuth AI")
st.caption("Graph-powered cyber investigations • FalkorDB is the source of truth")

with st.sidebar:
    st.subheader("Database")
    cfg = get_config()
    st.write(f"Host: `{cfg['host']}:{cfg['port']}`")
    if st.button("Check FalkorDB connection", use_container_width=True):
        try:
            ping_database()
            st.success("Connected to FalkorDB.")
        except Exception as exc:
            st.error(f"Connection failed: {exc}")
    if st.button("Load synthetic demo graph", type="primary", use_container_width=True):
        try:
            seed_demo_data()
            st.success("Synthetic nodes and relationships loaded.")
            st.rerun()
        except Exception as exc:
            st.error(f"Could not seed graph: {exc}")

st.info("Start FalkorDB first, then click **Load synthetic demo graph**. Data is fictional and for demonstration only.")

try:
    accounts = list_accounts()
except Exception as exc:
    st.error("FalkorDB is not reachable yet. Start the database and check your .env settings.")
    st.code(str(exc))
    st.stop()

if not accounts:
    st.warning("The graph is empty. Use **Load synthetic demo graph** in the sidebar.")
    st.stop()

account_options = {f"{row[1]} — {row[2]} risk ({row[0]})": row[0] for row in accounts}
selected_label = st.selectbox("Choose an account to investigate", list(account_options))
selected_id = account_options[selected_label]
session_key = st.session_state.setdefault("session_key", "browser-session")

if st.button("Trace graph evidence", type="primary"):
    try:
        st.session_state["last_investigation"] = investigate(selected_id, session_key)
    except Exception as exc:
        st.error(f"Investigation failed: {exc}")

result = st.session_state.get("last_investigation")
if result and result["account_id"] == selected_id:
    st.subheader("Investigation result")
    st.write(result["summary"])
    c1, c2, c3 = st.columns(3)
    c1.metric("Evidence paths", len(result["paths"]))
    c2.metric("Linked alerts", len(result["alerts"]))
    c3.metric("Investigation ID", result["investigation_id"][-8:])

    st.subheader("Graph evidence: Account → Device → Server")
    if result["paths"]:
        rows = []
        for row in result["paths"]:
            rows.append({
                "Account": row[1],
                "Risk": row[2],
                "Device": row[5],
                "Device status": row[6],
                "Server": row[7],
                "Sensitivity": row[8],
                "Observed at": row[9],
            })
        st.dataframe(rows, use_container_width=True, hide_index=True)
    else:
        st.warning("No matching path was found. The agent does not invent one.")

    if result["alerts"]:
        st.subheader("Related alerts")
        st.dataframe(
            [{"Alert": r[1], "Severity": r[2], "ID": r[0]} for r in result["alerts"]],
            use_container_width=True, hide_index=True
        )

    st.caption("Evidence is returned by Cypher queries over FalkorDB, not generated by an LLM.")

st.divider()
st.subheader("Persistent investigation memory")
if st.button("Load saved investigations for this account"):
    try:
        memory = get_memory(selected_id)
        st.session_state["memory_rows"] = memory
    except Exception as exc:
        st.error(f"Could not load graph memory: {exc}")

memory = st.session_state.get("memory_rows", [])
if memory:
    st.dataframe(
        [{"Question": r[0], "Summary": r[1], "Saved at (UTC)": r[2]} for r in memory],
        use_container_width=True, hide_index=True
    )
else:
    st.caption("Run an investigation, then load memory. History is stored in FalkorDB and survives browser refreshes.")
